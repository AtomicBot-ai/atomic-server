#!/usr/bin/env node
// docs/commands.md from the command specs, so the reference can never drift from `--help`.
// Needs `npm run build` first (it imports dist/). `--check` fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const { ROOT: tree } = await import(pathToFileURL(join(ROOT, 'dist/commands/index.js')).href)
const { renderHelp, walkCommands } = await import(pathToFileURL(join(ROOT, 'dist/cli/index.js')).href)

const out = [
  '# atc commands',
  '',
  'Generated by `npm run docs:commands` from the command specs. Do not edit by hand.',
  '',
]
out.push('| Command | Summary | Status |', '|---|---|---|')
for (const { spec, path } of walkCommands(tree)) {
  if (spec.hidden) continue
  const key = path.join(' ')
  const status = spec.subcommands ? 'group' : 'works'
  out.push(`| \`atc ${key}\` | ${spec.summary} | ${status} |`)
}
out.push('', '## Help texts', '')
for (const { spec, path } of walkCommands(tree)) {
  if (spec.hidden) continue
  out.push(
    `### atc ${path.join(' ')}`,
    '',
    '```',
    renderHelp(spec, path, { width: 100 }).trimEnd(),
    '```',
    ''
  )
}
const text = `${out.join('\n')}\n`
const target = join(ROOT, 'docs/commands.md')
if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(target, 'utf8')
    } catch {
      return ''
    }
  })()
  if (current !== text) {
    console.error('docs/commands.md is stale; run `npm run docs:commands`')
    process.exit(1)
  }
  console.log('docs/commands.md is current')
} else {
  writeFileSync(target, text)
  console.log(`wrote ${target}`)
}
