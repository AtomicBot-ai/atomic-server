#!/usr/bin/env node
// Embed the admin SPA into the binary as a generated module (the core's static-assets pattern):
// every file under packages/admin-ui/dist, gzipped and base64-encoded, keyed by its path. Without a
// built SPA the placeholder page is embedded instead, so tests and `build:bin` never need Vite.
//
//   node scripts/embed-admin-assets.mjs
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { extname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const DIST = join(ROOT, 'packages/admin-ui/dist')
const PLACEHOLDER = join(ROOT, 'resources/admin-placeholder.html')
const TARGET = join(ROOT, 'src/admin/static-assets.generated.ts')

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.mp4': 'video/mp4',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.txt': 'text/plain; charset=utf-8',
  '.map': 'application/json',
}

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const files = {}
let source
if (existsSync(join(DIST, 'index.html'))) {
  for (const file of walk(DIST)) files[relative(DIST, file).split('\\').join('/')] = readFileSync(file)
  source = 'packages/admin-ui/dist'
} else {
  files['index.html'] = readFileSync(PLACEHOLDER)
  source = 'resources/admin-placeholder.html (the SPA is not built)'
}

const hash = createHash('sha256')
const entries = Object.keys(files)
  .sort()
  .map((path) => {
    const body = files[path]
    hash.update(path).update(body)
    const type = TYPES[extname(path)] ?? 'application/octet-stream'
    return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, gz: ${JSON.stringify(gzipSync(body, { level: 9 }).toString('base64'))} },`
  })
const buildId = source.startsWith('resources') ? 'placeholder' : hash.digest('hex').slice(0, 16)

mkdirSync(join(ROOT, 'src/admin'), { recursive: true })
writeFileSync(
  TARGET,
  [
    `// Generated by scripts/embed-admin-assets.mjs from ${source}. Do not edit.`,
    '/* eslint-disable */',
    `export const ADMIN_BUILD_ID: string = ${JSON.stringify(buildId)}`,
    'export const ADMIN_ASSETS: Record<string, { type: string; gz: string }> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
)
console.log(
  `embedded ${entries.length} file(s) from ${source} → ${relative(ROOT, TARGET)} (build ${buildId})`
)
