#!/usr/bin/env node
// Write THIRD_PARTY_NOTICES.md: every package compiled into the `atc` binary, its license and the
// license text it ships. The binary bundles the root runtime dependencies (the core, Ink, React), the
// one devDependency the bundler resolves into it (`react-devtools-core`, see build-binaries.mjs), and
// the web admin's dependencies (embedded as the built SPA). Fails on a license the policy does not
// allow (`licenses.mjs`). CI runs it with --check; the release attaches the file.
//
//   node scripts/gen-third-party-notices.mjs           # write it
//   node scripts/gen-third-party-notices.mjs --check   # fail if it is not current
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { allowed, licenseOf } from './licenses.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md')
const BUNDLED_DEV = ['react-devtools-core']

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))

/** Node's lookup: `<dir>/node_modules/<name>`, then each parent up to the repository root. */
function resolvePackage(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    if (dir === ROOT || dirname(dir) === dir) return undefined
  }
}

function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(f) || /^licen[cs]e[-.]/i.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').trim() }))
}

const seen = new Map()
const problems = []

function visit(name, from, optional) {
  const dir = resolvePackage(name, from)
  if (!dir) {
    if (!optional) problems.push(`${name}: not installed (run \`bun install\`)`)
    return
  }
  const pkg = readJson(join(dir, 'package.json'))
  const key = `${pkg.name}@${pkg.version}`
  if (seen.has(key)) return
  const license = licenseOf(pkg)
  seen.set(key, { name: pkg.name, version: pkg.version, license, files: licenseFiles(dir) })
  if (!allowed(license)) problems.push(`${key}: license ${JSON.stringify(license)} is not allowed`)
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir, false)
  for (const dep of Object.keys(pkg.optionalDependencies ?? {})) visit(dep, dir, true)
}

const root = readJson(join(ROOT, 'package.json'))
for (const dep of Object.keys(root.dependencies ?? {})) visit(dep, ROOT, false)
for (const dep of BUNDLED_DEV) visit(dep, ROOT, false)
const adminDir = join(ROOT, 'packages', 'admin-ui')
const admin = readJson(join(adminDir, 'package.json'))
for (const dep of Object.keys(admin.dependencies ?? {})) visit(dep, adminDir, false)

if (problems.length) {
  console.error(`third-party notices: ${problems.length} problem(s)`)
  for (const p of problems) console.error(`  ${p}`)
  process.exit(1)
}

const packages = [...seen.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
)
const lines = [
  '# Third-party notices',
  '',
  'The `atc` binary includes the following packages. Generated by `scripts/gen-third-party-notices.mjs`;',
  'do not edit by hand.',
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
  '',
]
for (const p of packages) {
  lines.push(`## ${p.name} ${p.version}`, '', `License: ${p.license}`, '')
  if (p.files.length === 0)
    lines.push('(The package ships no license file; its package.json names the license above.)', '')
  for (const f of p.files) lines.push(`${f.file}:`, '', '````text', f.text, '````', '')
}
const text = `${lines.join('\n').trimEnd()}\n`

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== text) {
    console.error('THIRD_PARTY_NOTICES.md is not current; run `node scripts/gen-third-party-notices.mjs`')
    process.exit(1)
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${packages.length} packages)`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote THIRD_PARTY_NOTICES.md (${packages.length} packages)`)
}
